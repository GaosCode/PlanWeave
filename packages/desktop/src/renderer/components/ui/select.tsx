function SelectTrigger({
  className,
  size = "default",
  children,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Trigger> & {
  size?: "sm" | "default";
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        "flex w-fit items-center justify-between gap-1.5 rounded-lg border border-transparent bg-surface-muted py-2 pr-3 pl-2.5 text-sm whitespace-nowrap shadow-[inset_0_1px_1px_rgba(15,23,42,0.05)] transition-[color,background-color,box-shadow,border-color] outline-none select-none hover:bg-surface-muted/80 focus-visible:border-ring focus-visible:bg-surface-raised focus-visible:shadow-xs focus-visible:ring-3 focus-visible:ring-ring/50 disabled:cursor-not-allowed disabled:opacity-50 aria-invalid:border-destructive aria-invalid:ring-3 aria-invalid:ring-destructive/20 data-placeholder:text-muted-foreground data-[state=open]:border-ring data-[state=open]:bg-surface-raised data-[state=open]:shadow-xs data-[state=open]:ring-3 data-[state=open]:ring-ring/50 data-[state=open]:[&_svg]:rotate-180 data-[size=default]:h-8 data-[size=sm]:h-7 data-[size=sm]:rounded-[min(var(--radius-md),10px)] *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-1.5 dark:border-input dark:bg-input/30 dark:hover:bg-input/50 dark:focus-visible:bg-input/40 dark:data-[state=open]:bg-input/40 dark:aria-invalid:border-destructive/50 dark:aria-invalid:ring-destructive/40 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon asChild>
        <span className="flex size-5 shrink-0 items-center justify-center rounded-md bg-surface-raised/80 text-muted-foreground shadow-[inset_0_0_0_1px_rgba(15,23,42,0.06)] dark:bg-input/50">
          <ChevronDownIcon className="pointer-events-none size-3.5 transition-transform duration-150" />
        </span>
      </SelectPrimitive.Icon>
    </SelectPrimitive.Trigger>
  );
}

function SelectContent({
  className,
  children,
  position = "item-aligned",
  align = "center",
  showScrollDownHint = false,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content> & {
  /** Pin a bottom-only overflow cue; omit the top scroll button. */
  showScrollDownHint?: boolean;
}) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        data-align-trigger={position === "item-aligned"}
        className={cn(
          "relative z-50 max-h-(--radix-select-content-available-height) min-w-36 origin-(--radix-select-content-transform-origin) rounded-xl bg-popover p-1 text-popover-foreground shadow-lg ring-1 ring-foreground/10 duration-100 data-[align-trigger=true]:animate-none data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
          // Hint mode needs overflow on the viewport so only the bottom cue mounts.
          showScrollDownHint ? "overflow-hidden" : "overflow-x-hidden overflow-y-auto",
          position === "popper" &&
            "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
          className
        )}
        position={position}
        align={align}
        {...props}
      >
        <SelectPrimitive.Viewport
          data-position={position}
          className={cn(
            // Popper lists must grow with items; locking to trigger height collapses the menu.
            position === "popper" && "h-auto w-full min-w-(--radix-select-trigger-width)"
          )}
        >
          {children}
        </SelectPrimitive.Viewport>
        {showScrollDownHint ? <SelectScrollDownButton /> : null}
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  );
}

